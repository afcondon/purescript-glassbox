#!/usr/bin/env python3
"""Regenerate Probe.Fixture: every machine as a compiled-in PureScript literal.

Throwaway support for the node-vs-Go canonical-form check. The machines are
compiled in rather than read from disk so that what the probe proves is about
Glassbox.Canonical and the codec, not about whether a backend has filesystem
foreigns yet.
"""
import json, io, glob, os, subprocess

machines = [(os.path.basename(f)[:-5], json.load(open(f)))
            for f in sorted(glob.glob('core/machines/*.json'))]

sg = subprocess.run(
    ['git', '-C', '/Users/afc/work/afc-work/ShapedSteer/bosun', 'show',
     'glassbox-supervise-group:machines/supervise-group.json'],
    capture_output=True, text=True).stdout
if sg:
    machines.append(('supervise-group', json.loads(sg)))

# Everything the real corpus never does. The fractional and extreme defaults
# are the point: `Canonical.number` writes integers itself but reaches the
# backend's own float formatting for anything else, and that is the single
# construct in the module whose output is not identical by construction.
machines.append(('edge-cases', {
    "glassbox": 2,
    "id": "edge-cases",
    "title": "Quote \" backslash \\ tab \t end",
    "notes": ["a note with \"quotes\" and a \\backslash\\", "", "unicode: cafe — naive"],
    "initial": "a",
    "states": [{"id": "a", "label": "A \"quoted\""}, {"id": "b", "label": "B"}],
    "events": [{"id": "go", "label": "go\tthere"}],
    "config": [
        {"id": "ratio", "label": "Ratio", "default": 0.1},
        {"id": "third", "label": "Third", "default": 0.3333333333333333},
        {"id": "big", "label": "Big", "default": 1e21},
        {"id": "tiny", "label": "Tiny", "default": 5e-324},
        {"id": "neg", "label": "Neg", "default": -2.5},
        {"id": "round", "label": "Round", "default": 3.0},
        {"id": "name", "label": "Name", "default": "a \"b\" c"},
    ],
    "facts": [{"id": "f", "label": "F"}],
    "refusals": [{"id": "no", "text": "no \\ way"}],
    "commands": [],
    "rules": [
        {"from": "a", "on": "go", "cases": [
            {"when": {"op": "gt", "left": {"config": "ratio"}, "right": 0.25}, "to": "b"},
            {"when": {"fact": "f"}, "to": "a"},
            {"refuse": "no"}]},
        {"from": "b", "on": "go", "cases": [{"stay": True}]},
    ],
    "deadlines": [],
}))

def esc(x):
    return x.replace('\\', '\\\\').replace('"', '\\"')

rows = "\n  , ".join(
    'Tuple "%s" "%s"' % (n, esc(json.dumps(d, separators=(',', ':'), ensure_ascii=True)))
    for n, d in machines)

io.open('probe/src/Fixture.purs', 'w', encoding='utf-8').write(
'''-- | Generated by probe/gen-fixture.py. Throwaway.
module Probe.Fixture (machines) where

import Data.Tuple (Tuple(..))

machines :: Array (Tuple String String)
machines =
  [ %s
  ]
''' % rows)
print("machines: %d" % len(machines))
